/** Shayul mark: the loader silhouette, drawn plain (no tile). */
export function Mark({ size = 56, color = 'var(--sun)', title }: { size?: number; color?: string; title?: string }) {
  return (
    <svg
      viewBox="40 231 943 560"
      width={size}
      height={Math.round((size * 560) / 943)}
      role={title ? 'img' : undefined}
      aria-hidden={title ? undefined : true}
      aria-label={title}
      className="mark"
    >
      <path fill={color} d={LOADER_PATH} />
    </svg>
  )
}

export function LoaderMark({ size = 30, color = 'var(--sun)' }: { size?: number; color?: string }) {
  return <Mark size={size} color={color} />
}

export function Brand({ label, sub }: { label: string; sub?: string; onDark?: boolean }) {
  return (
    <>
      <span className="brand-mark">
        <Mark size={58} />
      </span>
      <span className="brand-text">
        <b>{label}</b>
        {sub ? <small>{sub}</small> : null}
      </span>
    </>
  )
}
