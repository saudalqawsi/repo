export const dict: Record<Locale, Dict> = { ar, en }
export const t = (l: Locale) => dict[l]
export const fill = (s: string, vars: Record<string, string | number>) =>
  s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''))

type TimeBasis = 'daily' | 'weekly' | 'monthly'
const AR_UNITS: Record<TimeBasis, { one: string; two: string; few: string; many: string }> = {
  daily: { one: 'يوم واحد', two: 'يومان', few: 'أيام', many: 'يومًا' },
  weekly: { one: 'أسبوع واحد', two: 'أسبوعان', few: 'أسابيع', many: 'أسبوعًا' },
  monthly: { one: 'شهر واحد', two: 'شهران', few: 'أشهر', many: 'شهرًا' },
}
/** "2 weeks" / "أسبوعان", with Arabic dual and plural forms. */
export function durationPhrase(locale: Locale, basis: TimeBasis, n: number) {
  if (locale === 'ar') {
    const u = AR_UNITS[basis]
    const num = new Intl.NumberFormat('ar-SA').format(n)
    if (n === 1) return u.one
    if (n === 2) return u.two
    return `${num} ${n <= 10 ? u.few : u.many}`
  }
  const en = { daily: ['day', 'days'], weekly: ['week', 'weeks'], monthly: ['month', 'months'] }[basis]
  return `${n} ${n === 1 ? en[0] : en[1]}`
}
